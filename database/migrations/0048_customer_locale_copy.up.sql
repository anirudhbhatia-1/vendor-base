-- Customer-surface copy in English and Hindi (MKT-11, UX-08).
--
-- The localisation machinery has existed since 0033 — server-held keys, a
-- /locale/bundle endpoint, a fetch helper — and carried thirty keys, of which
-- the customer app rendered five, on one screen, as a demonstration. Every
-- other string on every customer screen was a hardcoded English literal, and
-- the header's "EN / हिन्दी" control was a link to the account page.
--
-- These are the keys the rebuilt customer surface asks for. The English text is
-- also the literal fallback in the source, so a key that fails to load degrades
-- to English rather than to a bare `customer.cart.empty.title`.
--
-- `ON CONFLICT DO NOTHING` guards a re-run rather than an overlap: none of
-- these keys existed before this migration, and a corrected translation shipped
-- later must not be silently overwritten by re-applying this one.

